"""Action-conditioned ensemble world model.

The model predicts the next machine state, production level and one-step profit
from the current observation and a joint machine action. Training uses only data
generated by the independent reference plant. Uncertainty is represented by an
ensemble of independently initialized MLPs.
"""
from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Iterable

import numpy as np


def _relu(x: np.ndarray) -> np.ndarray:
    return np.maximum(x, 0.0)


def _sigmoid(x: np.ndarray) -> np.ndarray:
    return 1.0 / (1.0 + np.exp(-np.clip(x, -30.0, 30.0)))


class AdamMLP:
    """Small MLP with explicit NumPy backpropagation and Adam."""

    def __init__(self, input_dim: int, output_dim: int, hidden: int = 64, seed: int = 0) -> None:
        rng = np.random.default_rng(seed)
        self.W1 = rng.normal(0.0, np.sqrt(2.0 / input_dim), (hidden, input_dim))
        self.b1 = np.zeros(hidden)
        self.W2 = rng.normal(0.0, np.sqrt(2.0 / hidden), (hidden, hidden))
        self.b2 = np.zeros(hidden)
        self.W3 = rng.normal(0.0, np.sqrt(2.0 / hidden), (output_dim, hidden))
        self.b3 = np.zeros(output_dim)
        self.params = ("W1", "b1", "W2", "b2", "W3", "b3")
        self.m = {k: np.zeros_like(getattr(self, k)) for k in self.params}
        self.v = {k: np.zeros_like(getattr(self, k)) for k in self.params}
        self.t = 0

    def forward(self, x: np.ndarray) -> tuple[np.ndarray, tuple[np.ndarray, ...]]:
        z1 = x @ self.W1.T + self.b1
        a1 = _relu(z1)
        z2 = a1 @ self.W2.T + self.b2
        a2 = _relu(z2)
        y = a2 @ self.W3.T + self.b3
        return y, (x, z1, a1, z2, a2)

    def predict(self, x: np.ndarray) -> np.ndarray:
        return self.forward(x)[0]

    def train_batch(
        self,
        x: np.ndarray,
        y: np.ndarray,
        lr: float = 1.5e-3,
        weight_decay: float = 1e-5,
        loss_weights: np.ndarray | None = None,
    ) -> float:
        pred, cache = self.forward(x)
        residual = pred - y
        if loss_weights is None:
            loss_weights = np.ones(pred.shape[1], dtype=float)
        loss = float(np.mean((residual ** 2) * loss_weights.reshape(1, -1)))
        n = max(1, x.shape[0])
        grad = (2.0 / n) * residual * loss_weights.reshape(1, -1)
        x0, z1, a1, z2, a2 = cache
        gW3 = grad.T @ a2
        gb3 = grad.sum(axis=0)
        ga2 = grad @ self.W3
        gz2 = ga2 * (z2 > 0.0)
        gW2 = gz2.T @ a1
        gb2 = gz2.sum(axis=0)
        ga1 = gz2 @ self.W2
        gz1 = ga1 * (z1 > 0.0)
        gW1 = gz1.T @ x0
        gb1 = gz1.sum(axis=0)
        grads = {"W1": gW1, "b1": gb1, "W2": gW2, "b2": gb2, "W3": gW3, "b3": gb3}
        self.t += 1
        beta1, beta2, eps = 0.9, 0.999, 1e-8
        for name in self.params:
            g = grads[name] + weight_decay * getattr(self, name)
            self.m[name] = beta1 * self.m[name] + (1.0 - beta1) * g
            self.v[name] = beta2 * self.v[name] + (1.0 - beta2) * (g * g)
            mhat = self.m[name] / (1.0 - beta1 ** self.t)
            vhat = self.v[name] / (1.0 - beta2 ** self.t)
            setattr(self, name, getattr(self, name) - lr * mhat / (np.sqrt(vhat) + eps))
        return loss


@dataclass
class EnsemblePrediction:
    mean: np.ndarray
    std: np.ndarray


class EnsembleWorldModel:
    """Ensemble action-conditioned next-state model."""

    def __init__(self, n_machines: int, ensemble_size: int = 5, hidden: int = 64, seed: int = 0) -> None:
        self.n_machines = int(n_machines)
        self.ensemble_size = int(ensemble_size)
        self.hidden = int(hidden)
        self.seed = int(seed)
        self.input_dim = self.n_machines * 5 + 5 + self.n_machines * 4
        self.output_dim = self.n_machines * 5 + 2
        self.models: list[AdamMLP] = []
        self.loss_weights = np.ones(self.output_dim, dtype=float)
        self.x_mean: np.ndarray | None = None
        self.x_std: np.ndarray | None = None
        self.y_mean: np.ndarray | None = None
        self.y_std: np.ndarray | None = None

    def _make_models(self) -> None:
        self.models = [
            AdamMLP(self.input_dim, self.output_dim, self.hidden, seed=self.seed + 1000 * i)
            for i in range(self.ensemble_size)
        ]

    def _input(self, states: np.ndarray, actions: np.ndarray) -> np.ndarray:
        return np.concatenate([states, actions], axis=1)

    def _target(self, next_states: np.ndarray, profits: np.ndarray, productions: np.ndarray) -> np.ndarray:
        machine_next = next_states[:, : self.n_machines * 5]
        prod = np.clip(productions / 200.0, -2.0, 4.0).reshape(-1, 1)
        profit = np.clip(profits / 1500.0, -4.0, 4.0).reshape(-1, 1)
        return np.concatenate([machine_next, prod, profit], axis=1)

    def fit(
        self,
        states: np.ndarray,
        actions: np.ndarray,
        next_states: np.ndarray,
        profits: np.ndarray,
        productions: np.ndarray,
        epochs: int = 45,
        batch_size: int = 256,
        lr: float = 1.5e-3,
        val_fraction: float = 0.15,
    ) -> dict[str, float]:
        x = self._input(states, actions)
        y = self._target(next_states, profits, productions)
        rng = np.random.default_rng(self.seed)
        idx = rng.permutation(len(x))
        n_val = max(1, int(len(x) * val_fraction))
        val_idx, train_idx = idx[:n_val], idx[n_val:]
        xt, yt = x[train_idx], y[train_idx]
        xv, yv = x[val_idx], y[val_idx]
        self.x_mean, self.x_std = xt.mean(axis=0), xt.std(axis=0) + 1e-6
        self.y_mean, self.y_std = yt.mean(axis=0), yt.std(axis=0) + 1e-6
        xtn = (xt - self.x_mean) / self.x_std
        ytn = (yt - self.y_mean) / self.y_std
        xvn = (xv - self.x_mean) / self.x_std
        yvn = (yv - self.y_mean) / self.y_std
        self._make_models()
        train_losses: list[float] = []
        val_losses: list[float] = []
        for model in self.models:
            local_rng = np.random.default_rng(self.seed + 100 * len(train_losses) + 7)
            last_batch_loss = 0.0
            for _ in range(epochs):
                order = local_rng.permutation(len(xtn))
                for start in range(0, len(order), batch_size):
                    batch = order[start : start + batch_size]
                    last_batch_loss = model.train_batch(xtn[batch], ytn[batch], lr=lr, loss_weights=self.loss_weights)
            train_losses.append(float(np.mean((model.predict(xtn) - ytn) ** 2)))
            val_losses.append(float(np.mean((model.predict(xvn) - yvn) ** 2)))
        return {
            "train_loss": float(np.mean(train_losses)),
            "val_loss": float(np.mean(val_losses)),
            "n_train": float(len(train_idx)),
            "n_val": float(len(val_idx)),
        }

    def predict_raw(self, states: np.ndarray, actions: np.ndarray) -> EnsemblePrediction:
        if not self.models:
            raise RuntimeError("world model has not been fitted")
        assert self.x_mean is not None and self.y_mean is not None
        x = self._input(states, actions)
        xn = (x - self.x_mean) / self.x_std
        preds = np.stack([m.predict(xn) for m in self.models], axis=0)
        yn = preds.mean(axis=0)
        y_std = preds.std(axis=0)
        y = yn * self.y_std + self.y_mean
        # Standard deviation is interpreted in normalized output units.
        return EnsemblePrediction(mean=y, std=y_std)

    def predict_step(self, state: np.ndarray, mode: np.ndarray) -> tuple[np.ndarray, float, float]:
        from .plant import encode_modes

        action = encode_modes(mode, self.n_machines).reshape(1, -1)
        pred = self.predict_raw(state.reshape(1, -1), action)
        out = pred.mean[0]
        machine_next = out[: self.n_machines * 5]
        next_state = state.copy()
        next_state[: self.n_machines * 5] = machine_next
        next_state[-5] = np.clip(out[-2], 0.0, 3.0)  # total produced
        profit = float(out[-1] * 1500.0)
        uncertainty = float(np.mean(pred.std[0]))
        return next_state, profit, uncertainty

    def save(self, path: str | Path) -> None:
        payload = {
            "n_machines": self.n_machines,
            "ensemble_size": self.ensemble_size,
            "hidden": self.hidden,
            "seed": self.seed,
            "x_mean": self.x_mean,
            "x_std": self.x_std,
            "y_mean": self.y_mean,
            "y_std": self.y_std,
            "n_models": len(self.models),
        }
        for i, model in enumerate(self.models):
            for name in model.params:
                payload[f"m{i}_{name}"] = getattr(model, name)
        np.savez(path, **payload)

    @classmethod
    def load(cls, path: str | Path) -> "EnsembleWorldModel":
        data = np.load(path, allow_pickle=False)
        model = cls(
            n_machines=int(data["n_machines"]),
            ensemble_size=int(data["ensemble_size"]),
            hidden=int(data["hidden"]),
            seed=int(data["seed"]),
        )
        model.x_mean = data["x_mean"]
        model.x_std = data["x_std"]
        model.y_mean = data["y_mean"]
        model.y_std = data["y_std"]
        model.models = []
        for i in range(int(data["n_models"])):
            mlp = AdamMLP(model.input_dim, model.output_dim, model.hidden, seed=model.seed + 1000 * i)
            for name in mlp.params:
                setattr(mlp, name, data[f"m{i}_{name}"])
            model.models.append(mlp)
        return model
